function normalizePolarity(polarity) {
  const POSITIVE_SUBCATEGORIES = ['qualite_des_soins', 'confort_physique'];
  const NEGATIVE_SUBCATEGORIES = ['gestion_administrative', 'gestion_de_temps', 'conditions_d_accueil'];

  if (POSITIVE_SUBCATEGORIES.includes(polarity)) return 'Positive';
  if (NEGATIVE_SUBCATEGORIES.includes(polarity)) return 'Négative';

  // Valeur déjà correcte ("Positive", "Négative", "Neutre")
  return polarity;
}

function normalizeAnswers(answers) {
  const normalized = { ...answers };
  for (const key of ['q2', 'q3', 'q4']) {
    if (normalized[key] && typeof normalized[key] === 'object') {
      normalized[key] = {
        ...normalized[key],
        polarity: normalizePolarity(normalized[key].polarity)
      };
    }
  }
  return normalized;
}

